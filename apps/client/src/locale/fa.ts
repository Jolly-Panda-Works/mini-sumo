export const fa: Record<string, string> = Object.fromEntries(entries.trim().split('\n').map(line => {
  const separator = line.indexOf('|');
  return [line.slice(0, separator), line.slice(separator + 1)];
}));

/** Translate only display text; never call this on names, codes or input values. */
export function translate(text: string): string {
  const key = text.trim().replace(/\s+/g, ' ');
  const value = fa[key];
  if (value) return text.replace(text.trim(), value);
  return text;
}
